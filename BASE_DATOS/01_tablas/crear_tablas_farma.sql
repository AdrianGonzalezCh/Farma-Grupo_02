-- ============================================
-- CREACION DE TABLAS DEL PROYECTO FARMA
-- ============================================

-- Tabla de roles del sistema.
CREATE TABLE ROL (
    ID_ROL NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE VARCHAR2(50) NOT NULL,
    DESCRIPCION VARCHAR2(150),
    ESTADO VARCHAR2(15) DEFAULT 'ACTIVO' NOT NULL,
    CONSTRAINT PK_ROL PRIMARY KEY (ID_ROL),
    CONSTRAINT UQ_ROL_NOMBRE UNIQUE (NOMBRE)
);

-- Tabla de usuarios del sistema.
CREATE TABLE USUARIO (
    ID_USUARIO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_ROL NUMBER NOT NULL,
    CEDULA VARCHAR2(20) NOT NULL,
    NOMBRE VARCHAR2(60) NOT NULL,
    APELLIDO1 VARCHAR2(60) NOT NULL,
    APELLIDO2 VARCHAR2(60),
    CORREO VARCHAR2(100),
    USERNAME VARCHAR2(50) NOT NULL,
    CLAVE VARCHAR2(100) NOT NULL,
    ESTADO VARCHAR2(15) DEFAULT 'ACTIVO' NOT NULL,
    CONSTRAINT PK_USUARIO PRIMARY KEY (ID_USUARIO),
    CONSTRAINT UQ_USUARIO_CEDULA UNIQUE (CEDULA),
    CONSTRAINT UQ_USUARIO_CORREO UNIQUE (CORREO),
    CONSTRAINT UQ_USUARIO_USERNAME UNIQUE (USERNAME)
);

-- Tabla de pacientes.
CREATE TABLE PACIENTE (
    ID_PACIENTE NUMBER GENERATED BY DEFAULT AS IDENTITY,
    CEDULA VARCHAR2(20) NOT NULL,
    NOMBRE VARCHAR2(60) NOT NULL,
    APELLIDO1 VARCHAR2(60) NOT NULL,
    APELLIDO2 VARCHAR2(60),
    TELEFONO VARCHAR2(20),
    CORREO VARCHAR2(100),
    ESTADO VARCHAR2(15) DEFAULT 'ACTIVO' NOT NULL,
    CONSTRAINT PK_PACIENTE PRIMARY KEY (ID_PACIENTE),
    CONSTRAINT UQ_PACIENTE_CEDULA UNIQUE (CEDULA)
);

-- Tabla de medicos.
CREATE TABLE MEDICO (
    ID_MEDICO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE VARCHAR2(60) NOT NULL,
    APELLIDO1 VARCHAR2(60) NOT NULL,
    APELLIDO2 VARCHAR2(60),
    NUMERO_COLEGIADO VARCHAR2(30) NOT NULL,
    ESPECIALIDAD VARCHAR2(80),
    TELEFONO VARCHAR2(20),
    CORREO VARCHAR2(100),
    ESTADO VARCHAR2(15) DEFAULT 'ACTIVO' NOT NULL,
    CONSTRAINT PK_MEDICO PRIMARY KEY (ID_MEDICO),
    CONSTRAINT UQ_MEDICO_COLEGIADO UNIQUE (NUMERO_COLEGIADO)
);

-- Tabla de medicamentos.
CREATE TABLE MEDICAMENTO (
    ID_MEDICAMENTO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    CODIGO VARCHAR2(30) NOT NULL,
    NOMBRE VARCHAR2(100) NOT NULL,
    PRESENTACION VARCHAR2(100),
    REQUIERE_RECETA VARCHAR2(2) DEFAULT 'SI' NOT NULL,
    STOCK_ACTUAL NUMBER DEFAULT 0 NOT NULL,
    STOCK_MINIMO NUMBER DEFAULT 0 NOT NULL,
    ESTADO VARCHAR2(15) DEFAULT 'ACTIVO' NOT NULL,
    CONSTRAINT PK_MEDICAMENTO PRIMARY KEY (ID_MEDICAMENTO),
    CONSTRAINT UQ_MEDICAMENTO_CODIGO UNIQUE (CODIGO)
);

-- Tabla de recetas.
CREATE TABLE RECETA (
    ID_RECETA NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_PACIENTE NUMBER NOT NULL,
    ID_MEDICO NUMBER NOT NULL,
    FECHA_EMISION DATE DEFAULT SYSDATE NOT NULL,
    ESTADO VARCHAR2(15) DEFAULT 'ACTIVA' NOT NULL,
    OBSERVACIONES VARCHAR2(200),
    CONSTRAINT PK_RECETA PRIMARY KEY (ID_RECETA)
);

-- Tabla detalle de receta.
CREATE TABLE RECETA_DETALLE (
    ID_RECETA_DETALLE NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_RECETA NUMBER NOT NULL,
    ID_MEDICAMENTO NUMBER NOT NULL,
    DOSIS VARCHAR2(100),
    CANTIDAD_AUTORIZADA NUMBER NOT NULL,
    CANTIDAD_DISPENSADA NUMBER DEFAULT 0 NOT NULL,
    INDICACIONES VARCHAR2(200),
    CONSTRAINT PK_RECETA_DETALLE PRIMARY KEY (ID_RECETA_DETALLE)
);

-- Tabla encabezado de dispensacion.
CREATE TABLE DISPENSACION (
    ID_DISPENSACION NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_RECETA NUMBER NOT NULL,
    ID_USUARIO NUMBER NOT NULL,
    FECHA_DISPENSACION DATE DEFAULT SYSDATE NOT NULL,
    ESTADO VARCHAR2(15) DEFAULT 'ACTIVA' NOT NULL,
    OBSERVACIONES VARCHAR2(200),
    CONSTRAINT PK_DISPENSACION PRIMARY KEY (ID_DISPENSACION)
);

-- Tabla detalle de dispensacion.
CREATE TABLE DISPENSACION_DETALLE (
    ID_DISPENSACION_DETALLE NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_DISPENSACION NUMBER NOT NULL,
    ID_RECETA_DETALLE NUMBER NOT NULL,
    ID_MEDICAMENTO NUMBER NOT NULL,
    CANTIDAD_DISPENSADA NUMBER NOT NULL,
    CONSTRAINT PK_DISPENSACION_DETALLE PRIMARY KEY (ID_DISPENSACION_DETALLE)
);

-- Tabla de bitacora del sistema.
CREATE TABLE BITACORA (
    ID_BITACORA NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_USUARIO NUMBER NOT NULL,
    ACCION VARCHAR2(100) NOT NULL,
    ENTIDAD_AFECTADA VARCHAR2(50) NOT NULL,
    ID_REFERENCIA NUMBER,
    FECHA_HORA DATE DEFAULT SYSDATE NOT NULL,
    DETALLE VARCHAR2(200),
    CONSTRAINT PK_BITACORA PRIMARY KEY (ID_BITACORA)
);

-- Tabla de movimientos de inventario.
CREATE TABLE MOVIMIENTO_INVENTARIO (
    ID_MOVIMIENTO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_MEDICAMENTO NUMBER NOT NULL,
    TIPO_MOVIMIENTO VARCHAR2(20) NOT NULL,
    CANTIDAD NUMBER NOT NULL,
    MOTIVO VARCHAR2(150),
    FECHA_MOVIMIENTO DATE DEFAULT SYSDATE NOT NULL,
    ID_USUARIO NUMBER,
    CONSTRAINT PK_MOVIMIENTO_INVENTARIO PRIMARY KEY (ID_MOVIMIENTO)
);