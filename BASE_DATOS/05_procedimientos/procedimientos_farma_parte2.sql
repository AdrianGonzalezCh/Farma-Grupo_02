-- 17. Insertar receta.
CREATE OR REPLACE PROCEDURE SP_INSERTAR_RECETA (
    P_ID_PACIENTE    IN NUMBER,
    P_ID_MEDICO      IN NUMBER,
    P_OBSERVACIONES  IN VARCHAR2
)
AS
BEGIN
    INSERT INTO RECETA (
        ID_PACIENTE, ID_MEDICO, FECHA_EMISION, ESTADO, OBSERVACIONES
    ) VALUES (
        P_ID_PACIENTE, P_ID_MEDICO, SYSDATE, 'ACTIVA', P_OBSERVACIONES
    );
END;
/

-- 18. Consultar receta por ID.
CREATE OR REPLACE PROCEDURE SP_CONSULTAR_RECETA (
    P_ID_RECETA IN NUMBER,
    P_CURSOR OUT SYS_REFCURSOR
)
AS
BEGIN
    OPEN P_CURSOR FOR
        SELECT *
        FROM VW_RECETAS_ENCABEZADO
        WHERE ID_RECETA = P_ID_RECETA;
END;
/

-- 19. Insertar detalle de receta.
CREATE OR REPLACE PROCEDURE SP_INSERTAR_RECETA_DETALLE (
    P_ID_RECETA             IN NUMBER,
    P_ID_MEDICAMENTO        IN NUMBER,
    P_DOSIS                 IN VARCHAR2,
    P_CANTIDAD_AUTORIZADA   IN NUMBER,
    P_INDICACIONES          IN VARCHAR2
)
AS
BEGIN
    INSERT INTO RECETA_DETALLE (
        ID_RECETA, ID_MEDICAMENTO, DOSIS, CANTIDAD_AUTORIZADA, CANTIDAD_DISPENSADA, INDICACIONES
    ) VALUES (
        P_ID_RECETA, P_ID_MEDICAMENTO, P_DOSIS, P_CANTIDAD_AUTORIZADA, 0, P_INDICACIONES
    );
END;
/

-- 20. Actualizar estado de receta.
CREATE OR REPLACE PROCEDURE SP_ACTUALIZAR_ESTADO_RECETA (
    P_ID_RECETA IN NUMBER,
    P_ESTADO    IN VARCHAR2
)
AS
BEGIN
    UPDATE RECETA
    SET ESTADO = P_ESTADO
    WHERE ID_RECETA = P_ID_RECETA;
END;
