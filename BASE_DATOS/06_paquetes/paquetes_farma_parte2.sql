-------------------------------------------------
-- 7. PKG_BITACORA
-------------------------------------------------
CREATE OR REPLACE PACKAGE PKG_BITACORA AS
    PROCEDURE PR_REGISTRAR_BITACORA (
        P_ID_USUARIO        IN NUMBER,
        P_ACCION            IN VARCHAR2,
        P_ENTIDAD_AFECTADA  IN VARCHAR2,
        P_ID_REFERENCIA     IN NUMBER,
        P_DETALLE           IN VARCHAR2
    );

    PROCEDURE PR_CONSULTAR_BITACORA (
        P_CURSOR OUT SYS_REFCURSOR
    );
END PKG_BITACORA;
/
CREATE OR REPLACE PACKAGE BODY PKG_BITACORA AS
    PROCEDURE PR_REGISTRAR_BITACORA (
        P_ID_USUARIO        IN NUMBER,
        P_ACCION            IN VARCHAR2,
        P_ENTIDAD_AFECTADA  IN VARCHAR2,
        P_ID_REFERENCIA     IN NUMBER,
        P_DETALLE           IN VARCHAR2
    )
    AS
    BEGIN
        SP_REGISTRAR_BITACORA(
            P_ID_USUARIO, P_ACCION, P_ENTIDAD_AFECTADA, P_ID_REFERENCIA, P_DETALLE
        );
    END;

    PROCEDURE PR_CONSULTAR_BITACORA (
        P_CURSOR OUT SYS_REFCURSOR
    )
    AS
    BEGIN
        OPEN P_CURSOR FOR
            SELECT *
            FROM VW_BITACORA_RESUMEN
            ORDER BY FECHA_HORA DESC;
    END;
END PKG_BITACORA;
