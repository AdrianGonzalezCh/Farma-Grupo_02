-------------------------------------------------
-- 8. PKG_INVENTARIO
-------------------------------------------------
CREATE OR REPLACE PACKAGE PKG_INVENTARIO AS
    FUNCTION FN_STOCK_ACTUAL (
        P_ID_MEDICAMENTO IN NUMBER
    ) RETURN NUMBER;

    FUNCTION FN_STOCK_MINIMO (
        P_ID_MEDICAMENTO IN NUMBER
    ) RETURN NUMBER;

    PROCEDURE PR_AJUSTAR_STOCK (
        P_ID_MEDICAMENTO IN NUMBER,
        P_CANTIDAD       IN NUMBER
    );
END PKG_INVENTARIO;
/
CREATE OR REPLACE PACKAGE BODY PKG_INVENTARIO AS
    FUNCTION FN_STOCK_ACTUAL (
        P_ID_MEDICAMENTO IN NUMBER
    ) RETURN NUMBER
    AS
    BEGIN
        RETURN FN_STOCK_ACTUAL_MEDICAMENTO(P_ID_MEDICAMENTO);
    END;

    FUNCTION FN_STOCK_MINIMO (
        P_ID_MEDICAMENTO IN NUMBER
    ) RETURN NUMBER
    AS
    BEGIN
        RETURN FN_STOCK_MINIMO_MEDICAMENTO(P_ID_MEDICAMENTO);
    END;

    PROCEDURE PR_AJUSTAR_STOCK (
        P_ID_MEDICAMENTO IN NUMBER,
        P_CANTIDAD       IN NUMBER
    )
    AS
    BEGIN
        UPDATE MEDICAMENTO
        SET STOCK_ACTUAL = STOCK_ACTUAL + P_CANTIDAD
        WHERE ID_MEDICAMENTO = P_ID_MEDICAMENTO;
    END;
END PKG_INVENTARIO;
