/
CREATE OR REPLACE PACKAGE BODY PKG_REPORTES AS
    PROCEDURE PR_REPORTE_RECETAS_ACTIVAS (
        P_CURSOR OUT SYS_REFCURSOR
    )
    AS
    BEGIN
        OPEN P_CURSOR FOR
            SELECT *
            FROM VW_RECETAS_PENDIENTES;
    END;

    PROCEDURE PR_REPORTE_STOCK_BAJO (
        P_CURSOR OUT SYS_REFCURSOR
    )
    AS
    BEGIN
        OPEN P_CURSOR FOR
            SELECT *
            FROM VW_STOCK_BAJO;
    END;

    PROCEDURE PR_REPORTE_DISPENSACIONES (
        P_CURSOR OUT SYS_REFCURSOR
    )
    AS
    BEGIN
        OPEN P_CURSOR FOR
            SELECT *
            FROM VW_DISPENSACIONES_ENCABEZADO;
    END;
