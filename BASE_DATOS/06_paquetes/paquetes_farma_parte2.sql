CREATE OR REPLACE PACKAGE PKG_DISPENSACION AS
    PROCEDURE PR_INSERTAR_DISPENSACION (
        P_ID_RECETA        IN NUMBER,
        P_ID_USUARIO       IN NUMBER,
        P_OBSERVACIONES    IN VARCHAR2
    );

    PROCEDURE PR_DISPENSAR_MEDICAMENTO (
        P_ID_DISPENSACION        IN NUMBER,
        P_ID_RECETA_DETALLE      IN NUMBER,
        P_ID_MEDICAMENTO         IN NUMBER,
        P_CANTIDAD               IN NUMBER
    );

    PROCEDURE PR_ANULAR_DISPENSACION (
        P_ID_DISPENSACION IN NUMBER
    );
END PKG_DISPENSACION;
/
CREATE OR REPLACE PACKAGE BODY PKG_DISPENSACION AS
    PROCEDURE PR_INSERTAR_DISPENSACION (
        P_ID_RECETA        IN NUMBER,
        P_ID_USUARIO       IN NUMBER,
        P_OBSERVACIONES    IN VARCHAR2
    )
    AS
    BEGIN
        SP_INSERTAR_DISPENSACION(P_ID_RECETA, P_ID_USUARIO, P_OBSERVACIONES);
    END;

    PROCEDURE PR_DISPENSAR_MEDICAMENTO (
        P_ID_DISPENSACION        IN NUMBER,
        P_ID_RECETA_DETALLE      IN NUMBER,
        P_ID_MEDICAMENTO         IN NUMBER,
        P_CANTIDAD               IN NUMBER
    )
    AS
    BEGIN
        SP_DISPENSAR_MEDICAMENTO(
            P_ID_DISPENSACION, P_ID_RECETA_DETALLE, P_ID_MEDICAMENTO, P_CANTIDAD
        );
    END;

    PROCEDURE PR_ANULAR_DISPENSACION (
        P_ID_DISPENSACION IN NUMBER
    )
    AS
    BEGIN
        SP_ANULAR_DISPENSACION(P_ID_DISPENSACION);
    END;
END PKG_DISPENSACION;
